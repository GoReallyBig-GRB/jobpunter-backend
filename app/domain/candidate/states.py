EVIDENCE_DRAFT = "DRAFT"
EVIDENCE_PENDING_REVIEW = "PENDING_REVIEW"
EVIDENCE_APPROVED = "APPROVED"
EVIDENCE_REJECTED = "REJECTED"
EVIDENCE_ARCHIVED = "ARCHIVED"

_ALLOWED = {
    EVIDENCE_DRAFT: {EVIDENCE_PENDING_REVIEW, EVIDENCE_ARCHIVED},
    EVIDENCE_PENDING_REVIEW: {EVIDENCE_APPROVED, EVIDENCE_REJECTED, EVIDENCE_ARCHIVED},
    EVIDENCE_APPROVED: {EVIDENCE_ARCHIVED},
    EVIDENCE_REJECTED: {EVIDENCE_ARCHIVED, EVIDENCE_PENDING_REVIEW},
    EVIDENCE_ARCHIVED: set(),
}

def can_transition(current: str, target: str) -> bool:
    return target in _ALLOWED.get(current, set())
