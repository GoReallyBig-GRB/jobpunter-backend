CLAIM_DRAFT = "DRAFT"
CLAIM_PENDING_REVIEW = "PENDING_REVIEW"
CLAIM_APPROVED = "APPROVED"
CLAIM_REJECTED = "REJECTED"
CLAIM_ARCHIVED = "ARCHIVED"

_CLAIM_ALLOWED = {
    CLAIM_DRAFT: {CLAIM_PENDING_REVIEW, CLAIM_ARCHIVED},
    CLAIM_PENDING_REVIEW: {CLAIM_APPROVED, CLAIM_REJECTED, CLAIM_ARCHIVED},
    CLAIM_APPROVED: {CLAIM_ARCHIVED},
    CLAIM_REJECTED: {CLAIM_PENDING_REVIEW, CLAIM_ARCHIVED},
    CLAIM_ARCHIVED: set(),
}


def can_transition_claim(current: str, target: str) -> bool:
    return target in _CLAIM_ALLOWED.get(current, set())
